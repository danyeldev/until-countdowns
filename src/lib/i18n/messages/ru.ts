/**
 * Russian messages. See `en/` for what each key is for.
 *
 * Five decisions a maintainer should not undo:
 * - The ranking phrase is "Сколько дней до: {title}?" — heading, title, nav and share sheet all
 *   carry it. The colon is deliberate: `{title}` always arrives in the nominative ("Рождество",
 *   "Новый год", "Олимпийские игры") and Russian "до" governs the genitive, so a bare "Сколько
 *   дней до {title}?" would print "Сколько дней до Рождество?". The colon licenses the uninflected
 *   name and keeps the query prefix "сколько дней до" immediately in front of it, which is the
 *   whole point of the page — Russian search is lemmatised, so "до: Рождество" still matches
 *   "до рождества".
 * - No preposition ever stands in front of a placeholder. `{date}`, `{month}`, `{period}` and
 *   `{country}` come out of `Intl` in the nominative ("пятница, 25 декабря 2026 г.", "декабрь
 *   2026 г.", "Испания"), and "в"/"на"/"до" would each need a different case. Hence the em dash or
 *   a colon in front of every value — "{title} — {date}", "{month}: …", "с меткой «{country}»".
 * - Nothing ever puts a full stop after `{date}`, `{period}` or `{when}`. Russian `Intl` ends a
 *   long date with the abbreviation "г." ("пятница, 25 декабря 2026 г."), which already closes the
 *   sentence — a second dot would print "2026 г..". So those placeholders always sit last in their
 *   clause, and the next sentence simply follows the space.
 * - No verb or adjective agrees with a placeholder either: "{title} было отменено" is wrong for
 *   "Олимпийские игры", "Предстоящие {category}" is wrong for "Спорт" and "Кино". Every such
 *   template is turned around into a gender- and number-safe shape: "{title}: событие отменено",
 *   "{category}: предстоящие даты".
 * - `lowercaseCategory` is false. The label opens the hub title, the hub heading and the related
 *   heading, and Russian capitalises the first word of a title like any other sentence.
 * - Every plural carries one/few/many/other: Russian selects `one` for 1/21/31…, `few` for 2–4
 *   (22–24, …), `many` for 0 and 5–20, and `other` only for fractions ("1,5 дня"), which still has
 *   to be grammatical — genitive singular, not the `one` form.
 */
